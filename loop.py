# for loop (range)
for i in range(3):
    print("For loop:", i)

# for loop (list)
for fruit in ["apple", "banana"]:
    print("List item:", fruit)

# while loop
count = 0
while count < 3:
    print("While loop:", count)
    count += 1

# list comprehension
squares = [x**2 for x in range(3)]
print("Comprehension:", squares)